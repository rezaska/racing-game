export const CHAR_W = 5;
export const CHAR_H = 7;

const cache = new Map();
function glyph(ch) {
  let g = cache.get(ch);
  if (!g) {
    g = (G[ch] || G[' ']).split('|');
    cache.set(ch, g);
  }
  return g;
}

export function textWidth(str, scale = 1, tracking = 1) {
  return str.length * (CHAR_W + tracking) * scale - tracking * scale;
}

// align: 'left' | 'center' | 'right'
export function drawText(ctx, str, x, y, color, scale = 1, align = 'left', tracking = 1) {
  const s = String(str).toUpperCase();
  const w = textWidth(s, scale, tracking);
  let px = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? Math.round(x - w) : Math.round(x);

  ctx.fillStyle = color;
  ctx.beginPath();
  for (let i = 0; i < s.length; i++) {
    const rows = glyph(s[i]);
    for (let r = 0; r < CHAR_H; r++) {
      const row = rows[r];
      for (let c = 0; c < CHAR_W; c++) {
        if (row[c] === '#') ctx.rect(px + c * scale, y + r * scale, scale, scale);
      }
    }
    px += (CHAR_W + tracking) * scale;
  }
  ctx.fill();
}

// Text with a 1px drop shadow, which is what makes it readable over the road.
export function drawTextShadow(ctx, str, x, y, color, shadow, scale = 1, align = 'left') {
  drawText(ctx, str, x + scale, y + scale, shadow, scale, align);
  drawText(ctx, str, x, y, color, scale, align);
}
